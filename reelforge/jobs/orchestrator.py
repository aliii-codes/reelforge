    def _write_package(
        self,
        job: JobRecord,
        sv: ScriptVersion,
        manifest: SceneManifest,
        video_report: dict,
        timings: dict,
        render_cmd: list[str],
        music_note: str,
        cover_source: str,
    ) -> None:
        out = job.output_dir
        work = self.work_dir(job)
        hashtags = pkg.make_hashtags(sv.script)
        (out / "hashtags.txt").write_text(" ".join(hashtags) + "\n")
        (out / "caption.txt").write_text(pkg.make_caption(sv.script, sv.research, hashtags))
        (out / "script.md").write_text(pkg.script_markdown(sv, job.approved_hash))
        pkg.write_json(out / "sources.json", [s.model_dump(mode="json") for s in sv.research.sources])
        pkg.write_json(
            out / "claims.json",
            {
                "research_mode": sv.research.research_mode,
                "notes": sv.research.notes,
                "claims": [c.model_dump(mode="json") for c in sv.research.claims],
                "disclaimer": "auto_supported means the claim's key terms/numbers were found in source text that was "
                "actually retrieved; it is not proof. Review before publishing.",
            },
        )
        voice = json.loads((work / "voice.json").read_text()) if (work / "voice.json").exists() else {}
        takes = [r.model_dump(mode="json") for r in self.take_reports(job)]
        cap_val = (
            json.loads((work / "caption_validation.json").read_text())
            if (work / "caption_validation.json").exists()
            else {}
        )
        transcript = Transcript.model_validate_json((out / "transcript.json").read_text())
        pkg.write_json(
            out / "validation_report.json",
            {
                "generated_at": utcnow(),
                "video": video_report,
                "captions": cap_val,
                "scene_manifest": {"ok": not validate_manifest(manifest), "errors": validate_manifest(manifest)},
                "narration_takes": [{k: t[k] for k in ("index", "score", "wer", "duration", "issues")} for t in takes],
                "selected_take": self.db.get_job(job.id).selected_take,
                "limitations": [
                    "Transcript comparison catches missing/extra words; it does not prove pronunciation quality.",
                    "Avatar mouth uses loudness + letter-based viseme guesses, not phoneme-accurate lip-sync.",
                    "Claim checks are lexical matches against retrieved text, not proof of truth.",
                ],
            },
        )
        node_v = subprocess.run(
            ["node", "--version"], capture_output=True, text=True, check=False, env=remotion.node_env()
        ).stdout.strip()
        pkg.write_json(
            out / "render_metadata.json",
            {
                "job_id": job.id,
                "rendered_at": utcnow(),
                "script": {"version": sv.version, "sha256": job.approved_hash, "origin": sv.origin},
                "voice": voice,
                "transcription_model": transcript.model,
                "caption_timing": "word-level" if transcript.word_level else "segment-level (approximate)",
                "renderer": {
                    "remotion": remotion.remotion_version(self.settings.renderer_dir),
                    "node": node_v,
                    "ffmpeg": ff.ffmpeg_version(),
                    "command": render_cmd,
                },
                "output": {
                    "width": 1080,
                    "height": 1920,
                    "fps": manifest.fps,
                    "frames": manifest.duration_frames,
                    "video_codec": "h264",
                    "audio_codec": "aac",
                },
                "music": music_note,
                "sfx": "generated whooshes (original)" if self.config(job).sfx else "none",
                "cover": cover_source,
                "timings_seconds": timings,
                "stage_runs": [dict(r) | {"details_json": None} for r in self.db.stage_runs(job.id)],
                "platform": {"python": platform.python_version(), "machine": platform.platform()},
                "licences": LICENCES | ({"voice": voice.get("licence")} if voice else {}),
                "published": False,
            },
        )
        pkg.write_json(out / "project_config.json", self._project_config(self.db.get_job(job.id)))
        pkg.write_json(out / "package_manifest.json", pkg.check_package(out))
