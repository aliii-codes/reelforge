"""The pipeline: job creation, script versions and approval, stage execution, resume.

Stages after script approval: generating_voice -> aligning_captions -> planning_scenes ->
rendering -> awaiting_video_approval. Each stage reads its inputs from disk and writes its
outputs into the job directory, so a failed job resumes at the failing stage without
redoing earlier work.
"""

