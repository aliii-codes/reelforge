class PipelineError(RuntimeError):
    pass


class ApprovalIntegrityError(PipelineError):
    pass


def slugify(text: str, max_len: int = 32) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return (s[:max_len].rstrip("-")) or "reel"


class Pipeline:
    def __init__(
        self,
        settings: Settings,
        db: Database | None = None,
        log: Log = print,
        *,
        engine_factory: Callable[[JobConfig], VoiceEngine] | None = None,
        transcriber: Callable[[Path], Transcript] | None = None,
        renderer: Any = None,
        llm_factory: Callable[[str], FallbackLLM] | None = None,
    ):
        self.settings = settings
        settings.ensure_dirs()
        self.db = db or Database(settings.db_path)
        self.log = log
        self._engine_factory = engine_factory or self._default_engine
        self._transcriber = transcriber or self._default_transcriber
        self._renderer = renderer or remotion
        self._llm_factory = llm_factory or (lambda pref: FallbackLLM(configured_providers(settings, pref)))

    # ------------------------------------------------------------------ helpers

    def _default_engine(self, cfg: JobConfig) -> VoiceEngine:
        if cfg.voice_mode == "file":
            if not cfg.narration_file:
                raise PipelineError("voice_mode 'file' needs --narration PATH")
            from reelforge.voice.voiceover import ProcessingOptions

            return RecordedNarration(
                Path(cfg.narration_file),
                ProcessingOptions(
                    trim=cfg.vo_trim, max_pause=cfg.vo_max_pause, denoise=cfg.vo_denoise, normalize=cfg.vo_normalize
                ),
            )
        if cfg.voice_mode == "clone":
            from reelforge.voice.cloning import clone_engine

            return clone_engine(self.settings.voice_dir, cfg.voice_profile)
        from reelforge.voice.local_tts import stock_engine

        return stock_engine(cfg.stock_voice)

    def _default_transcriber(self, path: Path) -> Transcript:
        from reelforge.voice.transcription import transcribe

        return transcribe(path, self.settings.whisper_model, self.settings.whisper_threads)

    def job_dir(self, job: JobRecord) -> Path:
        return job.output_dir

    def work_dir(self, job: JobRecord) -> Path:
        d = job.output_dir / "work"
        d.mkdir(exist_ok=True)
        return d

    def config(self, job: JobRecord) -> JobConfig:
        return JobConfig.model_validate(job.config)

    def _new_job(self, title: str, topic: str, kind: str, cfg: JobConfig) -> JobRecord:
        stamp = datetime.now().strftime("%Y%m%d-%H%M")
        for _ in range(5):
            job_id = f"{stamp}-{slugify(title)}-{secrets.token_hex(2)}"
            out = pkg.safe_child(self.settings.output_dir, job_id)
            if not out.exists():
                break
        else:  # pragma: no cover
            raise PipelineError("could not allocate a unique job directory")
        out.mkdir(parents=True, exist_ok=False)  # never reuse/overwrite an existing job directory
        (out / "script_versions").mkdir()
        job = self.db.create_job(job_id, title, topic, kind, out, cfg.model_dump(mode="json"))
        pkg.write_json(out / "project_config.json", self._project_config(job))
        return job

    def _project_config(self, job: JobRecord) -> dict:
        return {
            "job_id": job.id,
            "reelforge_version": __version__,
            "created_at": job.created_at,
            "job_config": job.config,
            "settings": self.settings.public_dict(),  # secrets redacted to "set"/"missing"
        }

    # ------------------------------------------------------------------ script versions

    def save_version(
        self, job: JobRecord, script: Script, research: ResearchBundle, origin: str, note: str = ""
    ) -> ScriptVersion:
        existing = self.db.script_versions(job.id)
        version = (existing[-1]["version"] + 1) if existing else 1
        chk = validate_script(script, research)
        sv = ScriptVersion(
            version=version,
            origin=origin,
            note=note,
            script=script,
            research=research,
            warnings=chk.warnings + [f"ERROR: {e}" for e in chk.errors],
        )
        path = job.output_dir / "script_versions" / f"v{version}.json"
        if path.exists():
            raise PipelineError(f"{path} already exists; refusing to overwrite a script version")
        path.write_text(sv.model_dump_json(indent=2))
        os.chmod(path, 0o444)  # versions are immutable; edits create a new version
        self.db.add_script_version(job.id, sv, path)
        self.db.log(job.id, "script", f"saved script v{version} ({origin})")
        return sv

    def load_version(self, job: JobRecord, version: int | None = None) -> ScriptVersion:
        rows = self.db.script_versions(job.id)
        if not rows:
            raise PipelineError(f"job {job.id} has no script yet")
        row = rows[-1] if version is None else next((r for r in rows if r["version"] == version), None)
        if row is None:
            raise PipelineError(f"job {job.id} has no script v{version}")
        return ScriptVersion.model_validate_json(Path(row["path"]).read_text())

    def approved_version(self, job: JobRecord) -> ScriptVersion:
        if job.approved_version is None:
            raise PipelineError("the script has not been approved")
        sv = self.load_version(job, job.approved_version)
        if sv.content_hash() != job.approved_hash:
            raise ApprovalIntegrityError(
                f"approved script v{job.approved_version} was modified on disk after approval; "
                "create a new version with `revise` and approve it again"
            )
        return sv

    # ------------------------------------------------------------------ creation

    def create_from_script(self, script_file: Path, cfg: JobConfig, sources_file: Path | None = None) -> JobRecord:
        script, research, say = parse_script_file(script_file)
        if say:
            cfg = cfg.model_copy(update={"pronunciations": {**say, **cfg.pronunciations}})
        if cfg.handle == "" and script.handle:
            cfg = cfg.model_copy(update={"handle": script.handle})
        sources = list(research.sources)
        if sources_file:
            for s in parse_sources_file(sources_file):
                sources.append(s.model_copy(update={"id": f"M{len(sources) + 1}"}))
        job = self._new_job(script.title, script.topic, "script", cfg)
        notes = []
        if sources and cfg.fetch_sources:
            self.log(f"Opening {len(sources)} supplied source URL(s) to check them ...")
            sources = [fetch_source(s, self.settings.research_contact) for s in sources]
            opened = sum(s.fetched for s in sources)
            notes.append(f"{opened}/{len(sources)} supplied sources could be opened")
        claims = research.claims or extract_candidate_claims(script)
        if not research.claims and claims:
            notes.append("No [claim] lines in the script: factual sentences were auto-listed as unverified claims.")
        bundle = ResearchBundle(
            sources=sources,
            claims=assess_all(claims, sources),
            research_mode="manual" if sources else "none",
            notes=notes,
        )
        self.db.set_state(job.id, JobState.AWAITING_SCRIPT_APPROVAL)
        self.save_version(self.db.get_job(job.id), script, bundle, "manual", note=f"imported from {script_file.name}")
        return self.db.get_job(job.id)

    def create_from_topic(self, topic: str, cfg: JobConfig, sources_file: Path | None = None) -> JobRecord:
        job = self._new_job(topic, topic, "topic", cfg)
        if sources_file:
            shutil.copyfile(sources_file, self.work_dir(job) / "manual_sources.txt")
        return self._run_research(job)

    def _run_research(self, job: JobRecord) -> JobRecord:
        cfg = self.config(job)
        job = self.db.set_state(job.id, JobState.RESEARCHING)
        run_id = self.db.start_stage(job.id, JobState.RESEARCHING)
        t0 = time.time()
        try:
            manual_path = self.work_dir(job) / "manual_sources.txt"
            manual = parse_sources_file(manual_path) if manual_path.exists() else []
            llm = self._llm_factory(cfg.llm_provider)  # raises if no provider is configured
            if cfg.research:
                self.log("Researching (Wikipedia/Tavily search + opening pages) ...")
                research = gather_research(
                    job.topic,
                    tavily_key=self.settings.tavily_api_key,
                    contact=self.settings.research_contact,
                    extra_sources=manual,
                    fetch=cfg.fetch_sources,
                )
            else:
                research = ResearchBundle(
                    sources=manual,
                    research_mode="manual" if manual else "none",
                    notes=["research disabled for this job"],
                )
            self.log(f"  {len(research.sources)} sources ({sum(s.fetched for s in research.sources)} opened)")
            self.log("Generating hooks and script ...")
            result = generate_from_topic(job.topic, llm, research)
            result.research.notes.extend(result.notes)
            self.db.update_job(job.id, title=result.script.title)
            self.db.set_state(job.id, JobState.AWAITING_SCRIPT_APPROVAL)
            self.save_version(self.db.get_job(job.id), result.script, result.research, result.origin)
            self.db.finish_stage(run_id, True, time.time() - t0, details={"providers": result.notes})
        except Exception as e:
            self._fail(job.id, JobState.RESEARCHING, run_id, t0, e)
        return self.db.get_job(job.id)

    # ------------------------------------------------------------------ review / approval

    def revise(self, job_id: str, *, feedback: str | None = None, script_file: Path | None = None) -> ScriptVersion:
        job = self.db.get_job(job_id)
        if job.state not in (JobState.AWAITING_SCRIPT_APPROVAL, JobState.AWAITING_VIDEO_APPROVAL):
            raise PipelineError(f"cannot revise while the job is '{job.state}'")
        current = self.load_version(job)
        if script_file:
            script, research, say = parse_script_file(script_file)
            if not research.sources and not research.claims:
                research = current.research.model_copy(update={"claims": extract_candidate_claims(script)})
            research = research.model_copy(update={"claims": assess_all(research.claims, research.sources)})
            origin, note = "revision:manual", f"edited file {script_file.name}"
            if say:
                cfg = self.config(job).model_copy(update={"pronunciations": {**self.config(job).pronunciations, **say}})
                self.db.update_job(job.id, config_json=json.dumps(cfg.model_dump(mode="json")))
        elif feedback:
            result = revise_with_llm(
                current.script, current.research, feedback, self._llm_factory(self.config(job).llm_provider)
            )
            script, research, origin, note = result.script, result.research, result.origin, feedback
        else:
            raise PipelineError("give --feedback (LLM revision) or --file (manual edit)")
        if job.state == JobState.AWAITING_VIDEO_APPROVAL:
            self.db.set_state(job.id, JobState.AWAITING_SCRIPT_APPROVAL)
        self.db.update_job(job.id, approved_version=None, approved_hash=None)
        return self.save_version(self.db.get_job(job.id), script, research, origin, note)

    def approve_script(self, job_id: str, version: int | None = None) -> JobRecord:
        job = self.db.get_job(job_id)
        if job.state != JobState.AWAITING_SCRIPT_APPROVAL:
            raise PipelineError(f"job is '{job.state}', not awaiting script approval")
        cfg = self.config(job)
        if cfg.voice_mode == "file" and not cfg.narration_file:
            raise PipelineError(
                f"no voice-over attached yet: record one (voiceover-record --job {job.id}) or "
                f"attach a file (voiceover {job.id} --file ...) first"
            )
        sv = self.load_version(job, version)
        chk = validate_script(sv.script, sv.research)
        if not chk.ok:
            raise PipelineError("script has blocking problems: " + "; ".join(chk.errors))
        self.db.mark_version_approved(job.id, sv.version, sv.content_hash())
        self.db.log(job.id, "approval", f"script v{sv.version} approved (sha256 {sv.content_hash()[:12]})")
        return self.db.set_state(job.id, JobState.GENERATING_VOICE)

    def approve_video(self, job_id: str) -> JobRecord:
        job = self.db.get_job(job_id)
        if job.state != JobState.AWAITING_VIDEO_APPROVAL:
            raise PipelineError(f"job is '{job.state}', not awaiting video approval")
        check = pkg.check_package(job.output_dir)
        report = json.loads((job.output_dir / "validation_report.json").read_text())
        if not check["complete"]:
            raise PipelineError(f"package incomplete, missing: {check['missing']}")
        if not report.get("video", {}).get("ok"):
            raise PipelineError("video validation failed; fix and re-render before approving")
        now = utcnow()
        self.db.update_job(job.id, video_approved_at=now)
        pkg.write_json(
            job.output_dir / "approval.json",
            {
                "job_id": job.id,
                "script_version": job.approved_version,
                "script_sha256": job.approved_hash,
                "video_sha256": check["files"]["final_reel.mp4"]["sha256"],
                "approved_at": now,
                "note": "Approved by the user for publication. ReelForge never publishes automatically.",
            },
        )
        return self.db.set_state(job.id, JobState.COMPLETED)

    def request_rework(self, job_id: str, stage: JobState, note: str = "") -> JobRecord:
        job = self.db.get_job(job_id)
        if job.state not in (JobState.AWAITING_VIDEO_APPROVAL, JobState.AWAITING_PREVIEW_APPROVAL):
            raise PipelineError(f"job is '{job.state}', not awaiting preview or video approval")
        self.db.log(job.id, "rework", f"{job.state} sent back to {stage}: {note}")
        return self.db.set_state(job.id, stage)

    def approve_preview(self, job_id: str) -> JobRecord:
        job = self.db.get_job(job_id)
        if job.state != JobState.AWAITING_PREVIEW_APPROVAL:
            raise PipelineError(f"job is '{job.state}', not awaiting preview approval")
        self.db.log(job.id, "approval", "preview approved; starting final render")
        return self.db.set_state(job.id, JobState.RENDERING)

    def attach_voiceover(self, job_id: str, file: Path, **options: object) -> JobRecord:
        """Use a recorded voice-over for this job. The file is validated first and copied into
        the job folder; downstream stages are redone from the voice stage."""
        from reelforge.voice.voiceover import check_voiceover

        job = self.db.get_job(job_id)
        if job.state == JobState.COMPLETED:
            raise PipelineError("job is completed; create a new job for a new voice-over")
        chk = check_voiceover(file)
        if not chk.ok:
            raise PipelineError("voice-over rejected:\n  - " + "\n  - ".join(chk.errors))
        dest_dir = self.work_dir(job) / "voiceover_source"
        dest_dir.mkdir(exist_ok=True)
        dest = dest_dir / f"{datetime.now().strftime('%Y%m%d-%H%M%S')}{file.suffix.lower()}"
        shutil.copy2(file, dest)
        cfg = self.config(job).model_copy(
            update={"voice_mode": "file", "narration_file": str(dest), "takes": 1, **options}
        )
        JobConfig.model_validate(cfg.model_dump())  # re-validate option values
        self.db.update_job(job.id, config_json=json.dumps(cfg.model_dump(mode="json")))
        self.db.log(job.id, "voiceover", f"attached {file.name} as {dest.name}; options {options}")
        for w in chk.warnings:
            self.log(f"  voice-over warning: {w}")
        if job.state in (JobState.AWAITING_VIDEO_APPROVAL, JobState.AWAITING_PREVIEW_APPROVAL, JobState.FAILED):
            self.db.set_state(job.id, JobState.GENERATING_VOICE)
        return self.db.get_job(job.id)

    def select_take(self, job_id: str, index: int) -> JobRecord:
        job = self.db.get_job(job_id)
        reports = self.take_reports(job)
        if not any(r.index == index for r in reports):
            raise PipelineError(f"no take {index}; available: {[r.index for r in reports]}")
        if (
            job.state == JobState.AWAITING_VIDEO_APPROVAL
            or job.state == JobState.FAILED
            and job.failed_stage in POST_APPROVAL_STAGES[1:]
        ):
            self.db.set_state(job.id, JobState.ALIGNING_CAPTIONS)
        else:
            raise PipelineError(f"select a take after the voice stage (job is '{job.state}')")
        self._install_take(job, next(r for r in reports if r.index == index))
        self.db.update_job(job.id, selected_take=index)
        return self.db.get_job(job.id)

    # ------------------------------------------------------------------ running

    def run(self, job_id: str) -> JobRecord:
        stages = {
            JobState.GENERATING_VOICE: self._stage_voice,
            JobState.ALIGNING_CAPTIONS: self._stage_captions,
            JobState.PLANNING_SCENES: self._stage_scenes,
            JobState.PREVIEWING: self._stage_preview,
            JobState.RENDERING: self._stage_render,
        }
        job = self.db.get_job(job_id)
        while job.state in stages:
            stage = job.state
            self.log(f"== {stage} ==")
            run_id = self.db.start_stage(job.id, stage)
            t0 = time.time()
            try:
                details = stages[stage](job) or {}
            except Exception as e:
                self._fail(job.id, stage, run_id, t0, e)
                return self.db.get_job(job.id)
            self.db.finish_stage(run_id, True, time.time() - t0, details=details)
            self.log(f"   done in {time.time() - t0:.1f}s")
            nxt = next_stage(stage, self.config(job).preview_gate)
            assert nxt is not None
            job = self.db.set_state(job.id, nxt)
        return job

    def resume(self, job_id: str, from_stage: JobState | None = None) -> JobRecord:
        job = self.db.get_job(job_id)
        if from_stage is not None:
            if job.state != JobState.FAILED or from_stage not in POST_APPROVAL_STAGES:
                raise PipelineError("--from-stage only applies to a failed job and a post-approval stage")
            order = list(POST_APPROVAL_STAGES)
            if job.failed_stage in order and order.index(from_stage) > order.index(job.failed_stage):
                raise PipelineError(f"cannot skip past the failed stage '{job.failed_stage}'")
            self.db.set_state(job.id, from_stage)
            return self.run(job.id)
        if job.state == JobState.FAILED:
            target = job.failed_stage or JobState.GENERATING_VOICE
            if target == JobState.RESEARCHING:
                return self._run_research(job)
            self.db.set_state(job.id, target)
            return self.run(job.id)
        if job.state == JobState.CREATED and job.source_kind == "topic":
            return self._run_research(job)
        if job.state == JobState.RESEARCHING:  # interrupted mid-research: state was never left
            self.db.set_state(job.id, JobState.FAILED, error="interrupted", failed_stage=JobState.RESEARCHING)
            return self._run_research(self.db.get_job(job.id))
        if job.state in POST_APPROVAL_STAGES:
            return self.run(job.id)
        raise PipelineError(
            f"nothing to resume: job is '{job.state}'"
            + (" (approve the script first)" if job.state == JobState.AWAITING_SCRIPT_APPROVAL else "")
        )

    def _fail(self, job_id: str, stage: JobState, run_id: int, t0: float, e: Exception) -> None:
        msg = f"{type(e).__name__}: {e}"
        self.db.finish_stage(
            run_id, False, time.time() - t0, error=msg, details={"traceback": traceback.format_exc(limit=6)}
        )
        self.db.set_state(job_id, JobState.FAILED, error=msg, failed_stage=stage)
        self.log(f"!! stage '{stage}' failed: {msg}")
        self.log(f"   Fix the cause, then run: reelforge resume {job_id}")

    # ------------------------------------------------------------------ stages

    def take_reports(self, job: JobRecord) -> list[TakeReport]:
        p = self.work_dir(job) / "takes" / "takes_report.json"
        if not p.exists():
            return []
        return [TakeReport.model_validate(x) for x in json.loads(p.read_text())]

    def _install_take(self, job: JobRecord, take: TakeReport) -> None:
        shutil.copyfile(take.path, job.output_dir / "narration.wav")
        shutil.copyfile(take.transcript_path, job.output_dir / "transcript.json")

    def _archive(self, job: JobRecord, path: Path) -> None:
        if path.exists():
            dest = self.work_dir(job) / "archive" / datetime.now().strftime("%Y%m%d-%H%M%S")
            dest.mkdir(parents=True, exist_ok=True)
            shutil.move(str(path), dest / path.name)

    @staticmethod
    def _accepted_markers(identity: str, job: JobRecord, cfg: JobConfig) -> tuple[str, ...]:
        # Markers written before voice identities existed held only the script hash; they are
        # trusted for TTS jobs, never for a recorded voice-over.
        return (identity,) if cfg.voice_mode == "file" else (identity, job.approved_hash or "")

    def _voice_identity(self, cfg: JobConfig) -> str:
        """What the takes depend on besides the script; a change means regenerating them."""
        if cfg.voice_mode == "file" and cfg.narration_file and Path(cfg.narration_file).exists():
            parts = [
                pkg.sha256_file(Path(cfg.narration_file)),
                str(cfg.vo_trim),
                str(cfg.vo_max_pause),
                str(cfg.vo_denoise),
                str(cfg.vo_normalize),
            ]
        else:
            parts = [
                cfg.voice_mode,
                cfg.stock_voice,
                cfg.voice_profile,
                str(cfg.takes),
                str(cfg.speaking_rate),
                json.dumps(cfg.pronunciations, sort_keys=True),
            ]
        return "voice:" + "|".join(parts)

    def _stage_voice(self, job: JobRecord) -> dict:
        sv = self.approved_version(job)
        cfg = self.config(job)
        takes_dir = self.work_dir(job) / "takes"
        marker = takes_dir / "script_sha256.txt"
        identity = f"{job.approved_hash}|{self._voice_identity(cfg)}"
        if takes_dir.exists() and (
            not marker.exists() or marker.read_text().strip() not in self._accepted_markers(identity, job, cfg)
        ):
            self._archive(job, takes_dir)  # takes belong to an older script version or a different voice/recording
        takes_dir.mkdir(parents=True, exist_ok=True)
        marker.write_text(identity)
        engine = self._engine_factory(cfg)
        self.log(f"Voice: {engine.voice_label}")
        pkg.write_json(
            self.work_dir(job) / "voice.json",
            {
                "engine": engine.name,
                "voice_label": engine.voice_label,
                "provenance": engine.provenance,
                "licence": engine.licence_note,
                "voice_mode": cfg.voice_mode,
            },
        )
        reports = generate_takes(engine, sv.script, cfg, takes_dir, self._transcriber, self.log)
        best = best_take(reports)
        self._install_take(job, best)
        self.db.update_job(job.id, selected_take=best.index)
        self.log(
            f"Selected take {best.index} (score {best.score}). Others: "
            + ", ".join(f"#{r.index}={r.score}" for r in reports if r.index != best.index)
        )
        return {
            "takes": [{"index": r.index, "score": r.score, "wer": r.wer, "duration": r.duration} for r in reports],
            "selected": best.index,
        }

    def _stage_captions(self, job: JobRecord) -> dict:
        sv = self.approved_version(job)
        transcript = Transcript.model_validate_json((job.output_dir / "transcript.json").read_text())
        track = build_caption_track(sv.script, transcript, self.config(job).caption_source)
        expected = sum(len(s.text.split()) for s in sv.script.sections) if track.words_source == "script" else None
        report = validate_captions(track, transcript.duration, expected_words=expected)
        for note in track.notes:
            self.log(f"  {note}")
        (job.output_dir / "captions.json").write_text(track.model_dump_json(indent=1))
        pkg.write_json(self.work_dir(job) / "caption_validation.json", report.as_dict())
        if not report.ok:
            raise PipelineError("caption validation failed: " + "; ".join(report.errors[:5]))
        for w in report.warnings:
            self.log(f"  caption warning: {w}")
        return {"words": len(track.words), "groups": len(track.groups), "approximate": track.approximate_words}

    def _scene_plan_from_llm(self, job: JobRecord, script: Script) -> ScenePlanOut | None:
        cache = self.work_dir(job) / "llm_scene_plan.json"
        if cache.exists():
            return ScenePlanOut.model_validate_json(cache.read_text())
        if all(s.visual.scene or s.visual.headline for s in script.sections):
            return None  # the script already carries visual hints for every section
        try:
            llm = self._llm_factory(self.config(job).llm_provider)
            plan = llm.run(lambda p: p.generate_scene_plan(script))
        except Exception as e:  # scene planning falls back to heuristics
            self.log(f"  LLM scene plan unavailable ({type(e).__name__}); using heuristic planner")
            return None
        cache.write_text(plan.model_dump_json(indent=1))
        return plan

    def _stage_scenes(self, job: JobRecord) -> dict:
        sv = self.approved_version(job)
        cfg = self.config(job)
        track = CaptionTrack.model_validate_json((job.output_dir / "captions.json").read_text())
        narration = job.output_dir / "narration.wav"
        transcript = Transcript.model_validate_json((job.output_dir / "transcript.json").read_text())
        manifest = build_manifest(
            job_id=job.id,
            script=sv.script,
            track=track,
            research=sv.research,
            narration=narration,
            audio_duration=transcript.duration,
            handle=cfg.handle or self.settings.handle,
            plan=self._scene_plan_from_llm(job, sv.script),
        )
        errs = validate_manifest(manifest)
        if errs:
            raise PipelineError("scene manifest invalid: " + "; ".join(errs[:6]))
        (job.output_dir / "scene_manifest.json").write_text(manifest.model_dump_json(indent=1))
        public = self.work_dir(job) / "public"
        public.mkdir(exist_ok=True)
        shutil.copyfile(narration, public / "narration.wav")
        return {"scenes": [f"{s.id}:{s.type}" for s in manifest.scenes], "frames": manifest.duration_frames}

    def load_manifest(self, job: JobRecord) -> SceneManifest:
        p = job.output_dir / "scene_manifest.json"
        if not p.exists():
            raise PipelineError("no scene_manifest.json yet; run the pipeline up to scene planning first")
        m = SceneManifest.model_validate_json(p.read_text())
        errs = validate_manifest(m)
        if errs:
            raise PipelineError("scene_manifest.json is invalid: " + "; ".join(errs[:6]))
        return m

    def _silent_render_matches(
        self, silent: Path, stamp: Path, manifest_hash: str, manifest_path: Path, manifest: SceneManifest
    ) -> bool:
        """True if `silent` is a finished Remotion render of exactly this manifest.

        Normally proven by the hash stamp written after Remotion exits. If the process died
        before the stamp was written (e.g. machine shutdown during the audio mix), the file is
        adopted only if it is newer than the manifest, has the exact frame count/size/fps, and
        fully decodes. Remotion writes the output file only after all frames are rendered.
        """
        if stamp.exists() and stamp.read_text().strip() == manifest_hash:
            return True
        if silent.stat().st_mtime <= manifest_path.stat().st_mtime:
            return False
        proc = subprocess.run(
            [
                "ffprobe",
                "-v",
                "error",
                "-count_frames",
                "-select_streams",
                "v:0",
                "-show_entries",
                "stream=nb_read_frames,width,height,r_frame_rate",
                "-of",
                "json",
                str(silent),
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        try:
            st = json.loads(proc.stdout)["streams"][0]
        except (ValueError, KeyError, IndexError):
            return False
        ok = (
            int(st.get("nb_read_frames", 0)) == manifest.duration_frames
            and (st.get("width"), st.get("height")) == (manifest.width, manifest.height)
            and st.get("r_frame_rate") == f"{manifest.fps}/1"
            and not validation_decode_errors(silent)
        )
        if ok:
            stamp.write_text(manifest_hash)
            self.log("Verified an existing complete render of this manifest (frames, size, fps, full decode).")
        return ok

    def _build_mix(self, job: JobRecord, manifest: SceneManifest) -> tuple[Path, str]:
        """Narration + optional bed + beat-cued SFX -> work/mix.wav. Timing comes from the manifest,
        which is derived from the final narration."""
        cfg = self.config(job)
        work = self.work_dir(job)
        duration = manifest.duration_frames / manifest.fps
        music_path: Path | None = None
        music_note = "none"
        if cfg.music == "generated":
            music_path = work / "bed.wav"
            sound.write_bed(music_path, duration)
            music_note = "generated ambient bed (original, reelforge/rendering/sound.py)"
        elif cfg.music not in ("", "none"):
            music_path = Path(cfg.music)
            if not music_path.exists():
                raise PipelineError(f"music file not found: {music_path}")
            if not cfg.music_licence:
                raise PipelineError("a music file needs --music-licence describing its licence")
            music_note = f"user-supplied {music_path.name}; licence: {cfg.music_licence}"
        sfx_path: Path | None = None
        if cfg.sfx:
            sfx_path = work / "sfx.wav"
            if manifest.sfx_cues:
                cues = [(c.frame / manifest.fps, c.kind) for c in manifest.sfx_cues]
            else:  # manifests from before audio-driven editing
                cues = [(s.start_frame / manifest.fps, "whoosh") for s in manifest.scenes[1:]]
            sound.write_sfx_track(sfx_path, duration, cues)
        mix = work / "mix.wav"
        ff.run(
            ff.build_mix_command(
                narration=job.output_dir / "narration.wav",
                output=mix,
                duration=duration,
                music=music_path,
                music_db=cfg.music_volume_db,
                sfx=sfx_path,
                sfx_db=cfg.sfx_volume_db,
            )
        )
        return mix, music_note

    def _validate_output(self, video: Path, manifest: SceneManifest, cfg: JobConfig, scale: float = 1.0) -> dict:
        """Container/codec/size/fps/audio/decode/black/silence + render completion + caption sync."""
        w, h = even_dim(manifest.width * scale), even_dim(manifest.height * scale)
        report = validate_video(
            video,
            expected_duration=manifest.duration_frames / manifest.fps,
            target_min=cfg.target_min_seconds,
            target_max=cfg.target_max_seconds,
            width=w,
            height=h,
        )
        completion = check_render_completion(video, manifest.duration_frames)
        sync = caption_sync_report(video, manifest)
        report["render_completion"] = completion
        report["caption_timing"] = sync
        report["errors"] += completion["errors"] + sync["errors"]
        report["warnings"] += sync["warnings"]
        report["checks"] += ["frame count vs manifest", "caption timing vs audio onset/end and video length"]
        report["ok"] = not report["errors"]
        return report

    def _stage_preview(self, job: JobRecord) -> dict:
        """Low-resolution render with the real mix, a contact sheet and the same checks as the
        final render, so problems surface before the long full-resolution render."""
        ff.check_ffmpeg()
        cfg = self.config(job)
        manifest = self.load_manifest(job)
        out, work = job.output_dir, self.work_dir(job)
        scale = cfg.preview_scale
        self.log(
            f"Preview: {manifest.duration_frames} frames at {even_dim(1080 * scale)}x{even_dim(1920 * scale)} "
            f"(scale {scale:.2f}) ..."
        )
        silent = work / "preview_silent.mp4"
        t0 = time.time()
        res = self._renderer.render_video(
            self.settings.renderer_dir,
            props=out / "scene_manifest.json",
            public_dir=work / "public",
            output=silent,
            scale=scale,
            concurrency=cfg.render_concurrency,
            log=self.log,
            log_file=work / "remotion_preview.log",
        )
        render_s = round(time.time() - t0, 1)
        mix, _ = self._build_mix(job, manifest)
        ff.run(
            ff.build_mux_command(
                video=silent, audio=mix, output=out / "preview.mp4", duration=manifest.duration_frames / manifest.fps
            )
        )
        report = self._validate_output(out / "preview.mp4", manifest, cfg, scale=scale)
        make_contact_sheet(out / "preview.mp4", manifest, out / "preview_contact_sheet.jpg")
        report["render_seconds"] = render_s
        report["remotion_command"] = res.command
        pkg.write_json(out / "preview_report.json", report)
        if not report["ok"]:
            raise PipelineError("preview validation failed: " + "; ".join(report["errors"][:5]))
        for w in report["warnings"]:
            self.log(f"  preview warning: {w}")
        self.log(f"  preview: {out / 'preview.mp4'}  contact sheet: {out / 'preview_contact_sheet.jpg'}")
        return {"render_seconds": render_s, "summary": report["summary"]}

    def _stage_render(self, job: JobRecord) -> dict:
        ff.check_ffmpeg()
        sv = self.approved_version(job)
        cfg = self.config(job)
        manifest = self.load_manifest(job)
        out = job.output_dir
        work = self.work_dir(job)
        public = work / "public"
        timings: dict[str, float] = {}

        silent = work / "video_silent.mp4"
        stamp = work / "video_silent.manifest_sha256"
        manifest_hash = pkg.sha256_file(out / "scene_manifest.json")
        render_cmd: list[str]
        if silent.exists() and self._silent_render_matches(
            silent, stamp, manifest_hash, out / "scene_manifest.json", manifest
        ):
            # Resume after a later failure: the silent render already matches this manifest.
            self.log("Reusing the existing Remotion render (scene manifest unchanged).")
            timings["remotion_video"] = 0.0
            render_cmd = ["reused existing render"]
        else:
            self.log(
                f"Rendering {manifest.duration_frames} frames at 1080x1920 with Remotion "
                f"(concurrency {cfg.render_concurrency}) ..."
            )
            stamp.unlink(missing_ok=True)
            res = self._renderer.render_video(
                self.settings.renderer_dir,
                props=out / "scene_manifest.json",
                public_dir=public,
                output=silent,
                concurrency=cfg.render_concurrency,
                log=self.log,
                log_file=work / "remotion_render.log",
            )
            stamp.write_text(manifest_hash)
            timings["remotion_video"] = res.seconds
            render_cmd = res.command

        t0 = time.time()
        try:
            self._renderer.render_still(
                self.settings.renderer_dir,
                props=out / "scene_manifest.json",
                public_dir=public,
                output=out / "cover.png",
                log=self.log,
            )
            cover_source = "Remotion Cover composition"
        except Exception as e:  # fall back to a frame of the hook scene
            self.log(f"  cover still failed ({e}); using a video frame instead")
            ff.run(
                [
                    "ffmpeg",
                    "-v",
                    "error",
                    "-y",
                    "-ss",
                    "1.0",
                    "-i",
                    str(silent),
                    "-frames:v",
                    "1",
                    str(out / "cover.png"),
                ]
            )
            cover_source = "frame at 1.0s"
        timings["cover"] = round(time.time() - t0, 1)

        t0 = time.time()
        mix, music_note = self._build_mix(job, manifest)
        final_tmp = work / "final_reel.tmp.mp4"
        ff.run(
            ff.build_mux_command(
                video=silent, audio=mix, output=final_tmp, duration=manifest.duration_frames / manifest.fps
            )
        )
        self._archive(job, out / "final_reel.mp4")
        final_tmp.replace(out / "final_reel.mp4")
        timings["audio_mix_and_mux"] = round(time.time() - t0, 1)

        t0 = time.time()
        video_report = self._validate_output(out / "final_reel.mp4", manifest, cfg)
        timings["validation"] = round(time.time() - t0, 1)
        t0 = time.time()
        make_contact_sheet(out / "final_reel.mp4", manifest, out / "contact_sheet.jpg")
        timings["contact_sheet"] = round(time.time() - t0, 1)

        self._write_package(job, sv, manifest, video_report, timings, render_cmd, music_note, cover_source)
        if not video_report["ok"]:
            raise PipelineError("video validation failed: " + "; ".join(video_report["errors"][:5]))
        for w in video_report["warnings"]:
            self.log(f"  video warning: {w}")
        return {"timings": timings, "video": video_report["summary"]}

